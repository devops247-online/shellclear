//go:build ignore

// gen_builtin writes builtin_rules.go from patterns.yaml, so the binary does
// not parse YAML at start-up, which `motd` would pay in every new shell. Run
// `go generate ./internal/rules` after editing patterns.yaml;
// TestBuiltinMatchesYAML fails until the two agree.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"

	"gopkg.in/yaml.v3"
)

type rule struct {
	ID          string   `yaml:"id"`
	Name        string   `yaml:"name"`
	Test        string   `yaml:"test"`
	SecretGroup int      `yaml:"secret_group"`
	Severity    string   `yaml:"severity"`
	Keywords    []string `yaml:"keywords"`
}

func main() {
	src, err := os.ReadFile("patterns.yaml")
	if err != nil {
		log.Fatal(err)
	}
	dec := yaml.NewDecoder(bytes.NewReader(src))
	dec.KnownFields(true)
	var rules []rule
	if err := dec.Decode(&rules); err != nil {
		log.Fatal(err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by gen_builtin.go from patterns.yaml; DO NOT EDIT.\n\npackage rules\n\n")
	b.WriteString("// builtinRules is patterns.yaml decoded at build time.\nvar builtinRules = []ruleYAML{\n")
	for _, r := range rules {
		fmt.Fprintf(&b, "\t{ID: %s, Name: %s, Test: %s, SecretGroup: %d, Severity: %s, Keywords: %s},\n",
			strconv.Quote(r.ID), strconv.Quote(r.Name), strconv.Quote(r.Test), r.SecretGroup, strconv.Quote(r.Severity), quoteList(r.Keywords))
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("builtin_rules.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func quoteList(l []string) string {
	if l == nil {
		return "nil"
	}
	var b bytes.Buffer
	b.WriteString("[]string{")
	for i, s := range l {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(strconv.Quote(s))
	}
	b.WriteString("}")
	return b.String()
}
